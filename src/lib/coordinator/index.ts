/**
 * The app's view of case coordination.
 *
 * Every call site talks to this interface, and never to a Durable Object stub
 * directly. Two reasons, and the second is the one that matters:
 *
 * 1. `next dev` has no Durable Object binding, and the reviewer screens still
 *    have to work.
 * 2. A Durable Object stub is a network call dressed as a method call. Letting
 *    page components hold one would spread `idFromName` and RPC round trips
 *    through the UI layer, and the day the arbitration moves — to a facet, to
 *    a different key, to something that is not a DO at all — every one of them
 *    would need finding.
 */

export interface CaseCoordination {
  state(caseId: string): Promise<CoordinatorState>;
  /**
   * Who holds each case right now.
   *
   * The queue's question, and the one thing `idFromName(caseId)` cannot
   * answer: sixteen cases are sixteen objects, and an object addressed by one
   * case id knows nothing about the other fifteen. Behind the real
   * implementation this is one D1 query against a table those objects write
   * themselves; behind the stand-in it is a Map.
   *
   * Returns exactly what `buildRows` takes, so the queue, the rail and this
   * cannot drift into three different ideas of what a claim is.
   */
  held(): Promise<ReadonlyMap<string, CaseClaim>>;
  /**
   * `idempotencyKey` is generated by the CLIENT, once per intent.
   *
   * Client-side rather than server-side because the point is to recognise a
   * REPEAT of one intent, and only the client knows that two requests are the
   * same press of the same button. A key minted on the server would be new
   * every time and would recognise nothing.
   */
  claim(
    caseId: string,
    reviewerId: string,
    displayName: string,
    idempotencyKey?: string | null,
  ): Promise<ClaimOutcome>;
  release(
    caseId: string,
    reviewerId: string,
    idempotencyKey?: string | null,
  ): Promise<CoordinatorState>;
  rule(
    caseId: string,
    ruling: ReviewerRuling,
    idempotencyKey?: string | null,
  ): Promise<RuleOutcome>;
  /** Idempotent. `null` stands the clock down. */
  armClock(
    caseId: string,
    reference: string,
    dueOn: IsoDate | null,
  ): Promise<void>;
  /** Next public reference for `year`. `seed` is only used on a cold counter. */
  mintReference(year: number, seed: number): Promise<string>;
  /** False when this is the in-process stand-in and not the real thing. */
  readonly arbitrates: boolean;
}

// ---------------------------------------------------------------------------
// The real one
// ---------------------------------------------------------------------------

class DurableObjectCoordination implements CaseCoordination {
  readonly arbitrates = true;
  readonly #cases: CloudflareEnv["CASE_COORDINATOR"];
  readonly #minter: CloudflareEnv["REFERENCE_MINTER"];
  /** The mirror those objects write. Absent is a degraded read, not a crash. */
  readonly #db: D1Database | undefined;

  constructor(
    cases: CloudflareEnv["CASE_COORDINATOR"],
    minter: CloudflareEnv["REFERENCE_MINTER"],
    db: D1Database | undefined,
  ) {
    this.#cases = cases;
    this.#minter = minter;
    this.#db = db;
  }

  /**
   * `idFromName(caseId)` — exactly as CLAUDE.md specifies.
   *
   * Written out rather than using `getByName` so the addressing scheme is
   * legible at the call site: the case id IS the object's name, which is why
   * two reviewers on the same case reach the same instance and two reviewers
   * on different cases never contend.
   */
  #forCase(caseId: string) {
    return this.#cases.get(this.#cases.idFromName(caseId));
  }

  state(caseId: string): Promise<CoordinatorState> {
    return this.#forCase(caseId).state(caseId, new Date().toISOString());
  }

  /**
   * One query, not sixteen round trips.
   *
   * Read from the `claims` table rather than by fanning out across every
   * case's object, which is the shape this would otherwise take and which
   * grows with the queue. The objects write that table inside the same turn
   * they grant or release, so it lags only a failed write — and a stale mirror
   * costs a wrong row on a list, never a wrong arbitration, because the write
   * is refused at the object regardless of what this says.
   *
   * Every row is read and `claimIsLive` decides, rather than filtering with a
   * SQL comparison. ISO-8601 would compare correctly, so this is not about
   * whether it works: `WHERE expires_at > ?` is a SECOND liveness rule, and
   * the day the first one changes — a grace period, a different clock — it is
   * the copy nobody edits. The table is bounded by cases-ever-claimed, so
   * there is nothing to win by filtering in SQL anyway.
   *
   * Reading them all is also what makes the fixture holders work. A row exists
   * iff an object has spoken about that case, so a lapsed or released row is
   * exactly what must suppress the seed — excluding it in SQL would hand case
   * 105 back to A. Okonkwo the moment somebody released it. Same rule as
   * `#liveClaim` inside the object, so the queue and the case screen cannot
   * disagree about who holds what.
   */
  async held(): Promise<ReadonlyMap<string, CaseClaim>> {
    const now = new Date().toISOString();
    const claims = new Map<string, CaseClaim>();
    const spokenFor = new Set<string>();

    if (this.#db !== undefined) {
      try {
        const rows = await dbFrom(this.#db).select().from(schema.claims);
        for (const row of rows) {
          spokenFor.add(row.caseId);
          const parsed = StoredCaseClaim.safeParse(row);
          if (parsed.success && claimIsLive(parsed.data, now as IsoDateTime)) {
            claims.set(row.caseId, parsed.data);
          }
        }
      } catch {
        // No table yet, or D1 unreachable. The seeds below are still the
        // truthful part of the answer, and a queue that renders without live
        // claims beats a queue that does not render at all.
      }
    }

    for (const caseId of SEEDED_CASE_IDS) {
      if (spokenFor.has(caseId)) continue;
      const seed = seededHolder(caseId, now as IsoDateTime);
      if (seed !== null) claims.set(caseId, seed);
    }

    return claims;
  }

  claim(
    caseId: string,
    reviewerId: string,
    displayName: string,
    idempotencyKey: string | null = null,
  ): Promise<ClaimOutcome> {
    return this.#forCase(caseId).claim(
      caseId,
      reviewerId,
      displayName,
      new Date().toISOString(),
      idempotencyKey,
    );
  }

  release(
    caseId: string,
    reviewerId: string,
    idempotencyKey: string | null = null,
  ): Promise<CoordinatorState> {
    return this.#forCase(caseId).release(
      caseId,
      reviewerId,
      new Date().toISOString(),
      idempotencyKey,
    );
  }

  rule(
    caseId: string,
    ruling: ReviewerRuling,
    idempotencyKey: string | null = null,
  ): Promise<RuleOutcome> {
    return this.#forCase(caseId).rule(
      caseId,
      ruling,
      new Date().toISOString(),
      idempotencyKey,
    );
  }

  armClock(
    caseId: string,
    reference: string,
    dueOn: IsoDate | null,
  ): Promise<void> {
    return this.#forCase(caseId).armClock(caseId, reference, dueOn);
  }

  /** One instance for the whole application — that is the point of it. */
  mintReference(year: number, seed: number): Promise<string> {
    const stub = this.#minter.get(this.#minter.idFromName("case-reference"));
    return stub.next(year, seed);
  }
}

