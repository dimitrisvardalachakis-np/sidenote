/**
 * In-process coordination, for `next dev` and for tests.
 *
 * `arbitrates` is false and the UI says so, because this is the one stand-in
 * in the codebase whose difference from the real thing is invisible in normal
 * use and catastrophic in the case the feature exists for. A Map arbitrates
 * perfectly between two tabs on one developer's laptop and not at all between
 * two reviewers on two machines — and the screen looks identical either way.
 *
 * Named for what it is, like UnprotectedBotGate.
 */
class UnarbitratedCoordination implements CaseCoordination {
  readonly arbitrates = false;
  readonly #claims = new Map<string, CaseClaim>();
  readonly #rulings = new Map<string, ReviewerRuling>();
  readonly #counters = new Map<number, number>();
  /**
   * Replayed results, so a double-submit behaves the same here as on the real
   * object.
   *
   * Worth having even though this stand-in arbitrates nothing: if `next dev`
   * accepted a double-click that production collapses, the behaviour a
   * developer tests is not the behaviour that ships, and this is exactly the
   * kind of difference that is invisible until it is a duplicated ruling in a
   * regulatory log. No TTL — the map dies with the isolate, which is sooner
   * than any TTL would fire.
   */
  readonly #replays = new Map<string, unknown>();

  async #once<T>(key: string | null, work: () => Promise<T>): Promise<T> {
    if (key === null || key === "") return work();
    if (this.#replays.has(key)) return this.#replays.get(key) as T;
    const result = await work();
    this.#replays.set(key, result);
    return result;
  }

  /**
   * Same rule as the Durable Object's `#liveClaim`, for the same reason.
   *
   * A stored claim always wins and is expiry-filtered; the fixture holder
   * answers only where nothing is stored. A lapsed entry is KEPT rather than
   * deleted — deleting would return the case to never-spoken and the fixture
   * would spring back, so releasing case 105 would hand it to A. Okonkwo
   * again. The stand-in has to agree with the real object about this, or the
   * demo behaves differently under `next dev` than it does deployed, which is
   * the one thing a stand-in must never do.
   */
  #live(caseId: string, now: string): CaseClaim | null {
    const claim = this.#claims.get(caseId);
    if (claim === undefined) return seededHolder(caseId, now as IsoDateTime);
    return claimIsLive(claim, now) ? claim : null;
  }

  async state(caseId: string): Promise<CoordinatorState> {
    return {
      claim: this.#live(caseId, new Date().toISOString()),
      ruling: this.#rulings.get(caseId) ?? null,
      clock: null,
    };
  }

  /** The Map is the mirror here, and the seeds fold in on the same rule. */
  async held(): Promise<ReadonlyMap<string, CaseClaim>> {
    const now = new Date().toISOString();
    const claims = new Map<string, CaseClaim>();

    for (const [caseId, claim] of this.#claims) {
      if (claimIsLive(claim, now)) claims.set(caseId, claim);
    }

    for (const caseId of SEEDED_CASE_IDS) {
      if (this.#claims.has(caseId)) continue;
      const seed = seededHolder(caseId, now as IsoDateTime);
      if (seed !== null) claims.set(caseId, seed);
    }

    return claims;
  }

  async claim(
    caseId: string,
    reviewerId: string,
    displayName: string,
    idempotencyKey: string | null = null,
  ): Promise<ClaimOutcome> {
    return this.#once(idempotencyKey, async () => {
      const now = new Date().toISOString();
      const existing = this.#live(caseId, now);

      if (existing !== null && existing.reviewerId !== reviewerId) {
        return { kind: "held_by_other", claim: existing };
      }

      const claim: CaseClaim = {
        reviewerId,
        displayName,
        heldSince: existing?.heldSince ?? now,
        expiresAt: claimExpiryFrom(now),
      };

      this.#claims.set(caseId, claim);
      return existing === null
        ? { kind: "granted", claim }
        : { kind: "already_yours", claim };
    });
  }

  async release(
    caseId: string,
    reviewerId: string,
    idempotencyKey: string | null = null,
  ): Promise<CoordinatorState> {
    return this.#once(idempotencyKey, async () => {
      const now = new Date().toISOString();
      const existing = this.#live(caseId, now);
      // Lapsed, not deleted — see `#live`.
      if (existing?.reviewerId === reviewerId) {
        this.#claims.set(caseId, {
          ...existing,
          expiresAt: now as IsoDateTime,
        });
      }
      return this.state(caseId);
    });
  }

  async rule(
    caseId: string,
    ruling: ReviewerRuling,
    idempotencyKey: string | null = null,
  ): Promise<RuleOutcome> {
    return this.#once(idempotencyKey, async () => {
      const existing = this.#live(caseId, new Date().toISOString());
      if (existing === null) {
        return {
          ok: false,
          reason: "Claim this case before ruling on it.",
          state: await this.state(caseId),
        };
      }
      if (existing.reviewerId !== ruling.decidedBy) {
        return {
          ok: false,
          reason: `${existing.displayName} is holding this case.`,
          state: await this.state(caseId),
        };
      }
      this.#rulings.set(caseId, ruling);
      return { ok: true, reason: null, state: await this.state(caseId) };
    });
  }

  async armClock(
    _caseId: string,
    reference: string,
    dueOn: IsoDate | null,
  ): Promise<void> {
    // Standing a clock down is a no-op with nothing to stand down, so it says
    // nothing. The nightly sweep calls this for EVERY open case, most of which
    // want no clock at all, and logging those produced a failure line per case
    // per night — a wall of red about work nobody asked for, which is how a log
    // stops being read.
    if (dueOn === null) return;

    // There is no alarm without a Durable Object, and there is no honest way
    // to fake one — a setTimeout dies with the process and would be a promise
    // to notify that nothing keeps. So a clock that was genuinely WANTED and
    // cannot be armed is still reported, every time.
    audit({
      actor: "system",
      action: "arm_expedited_clock",
      target: reference,
      outcome: "failure",
      detail: { reason: "no_durable_object_bound", dueOn },
    });
  }

  async mintReference(year: number, seed: number): Promise<string> {
    const current = this.#counters.get(year) ?? Math.max(seed, 0);
    const next = current + 1;
    this.#counters.set(year, next);
    return `SN-${year}-${String(500_000 + next).padStart(6, "0")}`;
  }
}

const standIn = new UnarbitratedCoordination();

export async function getCaseCoordination(): Promise<CaseCoordination> {
  const env = await getCloudflareEnv();
  const cases = env?.CASE_COORDINATOR;
  const minter = env?.REFERENCE_MINTER;
  if (cases === undefined || minter === undefined) return standIn;
  // D1 may be absent while the objects are bound. That degrades `held()` to
  // the fixture holders and nothing else; it does not stop anyone claiming.
  return new DurableObjectCoordination(cases, minter, env?.DB);
}

